// App categories are a product crosswalk, not a government industry classification.
import {readFileSync,writeFileSync,readdirSync} from 'node:fs'
const rules=JSON.parse(readFileSync('data/occupations/category_rules.json','utf8'))
const cases=Object.entries(rules).sort(([a],[b])=>b.length-a.length||a.localeCompare(b)).map(([p,c])=>`      when m.code like '${p}%' then '${c}'`).join('\n')
const dir = ['supabase/pending','supabase/migrations'].find(d=>readdirSync(d).some(f=>f.endsWith('_occupation_category_auto.sql')))
const file=dir+'/'+readdirSync(dir).find(f=>f.endsWith('_occupation_category_auto.sql'))
const sql=`-- Generated by scripts/generate-occupation-category.mjs from category_rules.json.
-- 2026-10-22 Lee: derive the existing app category from the official occupation code.
-- No occupation/evidence/publication rule changes; no new data access or SECURITY DEFINER.
create or replace function public.category_for_occupation(p_code text)
returns text language sql stable security invoker set search_path = '' as $$
  select coalesce((select case
${cases}
      else 'khac' end from public.occupation_master m where m.code = p_code), 'khac');
$$;
revoke all on function public.category_for_occupation(text) from public;
grant execute on function public.category_for_occupation(text) to anon,authenticated,service_role;

create or replace function public.sync_occupation_category()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  new.category := public.category_for_occupation(new.occupation_code);
  return new;
end;
$$;
revoke all on function public.sync_occupation_category() from public;
-- Before policy evaluation; then again after R8 may clear an obsolete occupation/evidence.
create trigger trg_00_occupation_category before insert or update on public.local_jobs
for each row execute function public.sync_occupation_category();
create trigger trg_zzzy_occupation_category before insert or update on public.local_jobs
for each row execute function public.sync_occupation_category();

-- Only already classified rows with inconsistent categories. Production dry-run found zero.
update public.local_jobs set category=public.category_for_occupation(occupation_code)
where occupation_code is not null and category is distinct from public.category_for_occupation(occupation_code);
comment on function public.category_for_occupation(text) is
'QĐ34/2020 official occupation code to existing Viecganban menu category; longest prefix. Broad mixed groups use khac. No deeper occupation is inferred.';
`
if(process.argv.includes('--check')){if(readFileSync(file,'utf8')!==sql)throw new Error('occupation category SQL differs from canonical mapping')}else writeFileSync(file,sql)
