import { chromium } from 'playwright'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1366, height: 900 }, geolocation: { latitude: 21.10, longitude: 106.07 }, permissions: ['geolocation'] })
await ctx.addInitScript(() => { Object.defineProperty(Navigator.prototype, 'webdriver', { get: () => false }); try { localStorage.setItem('vgb_location_prompt_v1', 'allow') } catch {} })
const p = await ctx.newPage()
await p.goto('https://viecganban.vn/', { waitUntil: 'networkidle', timeout: 60000 })
const map = p.locator('.hme-map').first(); await map.scrollIntoViewIfNeeded(); await p.waitForTimeout(8000)
const txt = await p.locator('.hme').first().innerText()
for (const s of ['Độ chính xác vị trí', 'Chọn điểm trên bản đồ', 'đường chim bay', 'Xem trên Google Maps', 'Gọi hỏi đường']) console.log('text', s, txt.includes(s) ? 'STILL' : 'gone')
console.log('job pins', await p.locator('.hme-map__job-marker').count())
  await p.locator('.hme').first().screenshot({ path: 'cp-before.png' })
  const pin = p.locator('.hme-map__job-marker').first()
await pin.click({ force: true }).catch((e) => console.log('click err', e.message.slice(0, 80)))
await p.waitForTimeout(1500)
console.log('list', JSON.stringify((await p.locator('.hme').first().innerText()).match(/\d+ việc làm[^\n]*/g)))
  console.log('panel', await p.locator('.hme-job').count(), JSON.stringify(await p.locator('.hme-job__actions a').allTextContents()))
await p.locator('.hme').first().screenshot({ path: 'cp-pc.png' })
await b.close()
