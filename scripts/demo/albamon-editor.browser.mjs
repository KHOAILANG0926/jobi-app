// Every selection must have its own artwork; the thumbnail and document use the same source.
const artSources = [], renderedTemplates = []
for (let i = 0; i < 6; i++) {
  await run(`document.querySelector('[data-template="${i}"]').click()`)
  const thumb = await run(`document.querySelector('#template-list [data-template="${i}"] img').getAttribute('src')`)
  const body = await run(`document.querySelector('.template-document .hero img').getAttribute('src')`)
  assert.equal(thumb, body, `template ${i+1}: thumbnail matches body artwork`)
  artSources.push(body)
  const html = await run('JobEditor.getHTML()')
  assert.ok(html.includes(body), `template ${i+1}: preview/export uses selected artwork`)
  assert.ok(html.includes('수학 강사 모집'), `template ${i+1}: keeps authored title`)
  assert.equal(await run(`document.querySelector('.hero img').complete && document.querySelector('.hero img').naturalWidth > 0`),true,`template ${i+1}: selected illustration loads`)
  assert.equal(await run(`(() => {const d=document.createElement('div');d.innerHTML=JobEditor.getHTML();return d.querySelector('table').style.backgroundColor===document.querySelector('.template-document .hero table').style.backgroundColor && d.querySelector('table').rows.length===document.querySelector('.template-document .hero table').rows.length})()`),true,`template ${i+1}: preview preserves hero layout and background`)
  await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
  assert.ok(await run('document.documentElement.scrollWidth <= innerWidth'),`template ${i+1}: mobile fits`)
  await run(`document.querySelector('[data-action="preview-mobile"]').click()`)
  assert.ok((await run('document.querySelector("#preview-frame").srcdoc')).includes(body),`template ${i+1}: mobile preview artwork matches`)
  await run(`document.querySelector('[data-action="close-preview"]').click()`)
  await send('Emulation.setDeviceMetricsOverride',{width:1180,height:1100,deviceScaleFactor:1,mobile:false})
  renderedTemplates.push(html)
}
assert.equal(new Set(artSources).size,6,'all six templates have distinct artwork')
assert.equal(new Set(renderedTemplates).size,6,'all six templates render distinct documents')
