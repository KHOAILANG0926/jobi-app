import assert from 'node:assert/strict'
const pages = await (await fetch((process.env.CDP_URL || 'http://127.0.0.1:9222') + '/json')).json()
const page = pages.find(p => p.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
await new Promise(resolve => ws.addEventListener('open', resolve, { once: true }))
let id = 0
const pending = new Map()
ws.addEventListener('message', event => { const msg = JSON.parse(event.data); if(msg.id) { const p = pending.get(msg.id); pending.delete(msg.id); msg.error ? p.reject(msg.error) : p.resolve(msg.result) } })
const send = (method, params = {}) => new Promise((resolve, reject) => { const n = ++id; pending.set(n,{resolve,reject}); ws.send(JSON.stringify({id:n,method,params})) })
async function run(expression) { const r = await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true}); if(r.exceptionDetails) throw new Error(r.exceptionDetails.text+': '+JSON.stringify(r.exceptionDetails.exception)); return r.result.value }
await send('Page.enable')
await send('Page.navigate', {url:process.env.EDITOR_URL || 'http://127.0.0.1:8093/public/demos/albamon-editor/'})
await new Promise(resolve => setTimeout(resolve, 700))
assert.equal(await run('typeof window.JobEditor'), 'object', 'Editor exposes integration API')
assert.equal(await run('document.querySelectorAll("#template-list .template-card").length'), 6)
await run(`document.querySelector('[data-field="title"]').value='수학 강사 모집';document.querySelector('[data-field="title"]').dispatchEvent(new Event('input',{bubbles:true}));`)
await run(`document.querySelector('[data-template="3"]').click()`)
assert.equal(await run('JobEditor.getDocument().title'), '수학 강사 모집', 'template changes keep typed content')
await run(`document.querySelector('[data-color="#91c5dc"]').click()`)
assert.equal(await run('JobEditor.getDocument().color'), '#91c5dc')
const rows = await run('JobEditor.getDocument().roles.length')
await run(`document.querySelector('[data-action="add-row"]').click()`)
assert.equal(await run('JobEditor.getDocument().roles.length'), rows+1)
await run(`document.querySelector('[data-section="contact"]').click()`)
assert.equal(await run('JobEditor.getDocument().sections.includes("contact")'), true)
await run(`document.querySelector('[data-tab="editor"]').click()`)
assert.equal(await run('document.querySelector("#rich-editor").isContentEditable'), true)
await run(`document.querySelector('#rich-editor').innerHTML += '<p>추가 내용 유지</p>';document.querySelector('#rich-editor').dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('[data-mode="html"]').click()`)
assert.ok((await run('document.querySelector("#html-source").value')).includes('추가 내용 유지'))
await run(`document.querySelector('[data-tab="direct"]').click();document.querySelector('#html-source').value='<h2>안전한 공고</h2><script>parent.pwned=true<'+ '/script><img src=x onerror="parent.pwned=true"><a href="javascript:alert(1)">지원</a><iframe src="https://example.com"></iframe>';document.querySelector('#html-source').dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('[data-action="preview-pc"]').click()`)
const safe = await run('JobEditor.getHTML()')
assert.ok(!/<script|onerror|javascript:|<iframe/i.test(safe), 'sanitizes raw HTML')
assert.ok(safe.includes('안전한 공고'))
assert.equal(await run('document.querySelector("#preview-dialog").open'), true)
assert.equal(await run('document.querySelector("#preview-frame").getAttribute("sandbox")'), '')
await run(`document.querySelector('[data-action="preview-mobile"]').click()`)
assert.equal(await run('document.querySelector("#preview-frame").style.width'), '390px')
await run(`document.querySelector('[data-action="close-preview"]').click();document.querySelector('[data-tab="template"]').click()`)
assert.equal(await run('JobEditor.getDocument().title'), '수학 강사 모집')
await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
assert.ok(await run('document.documentElement.scrollWidth <= window.innerWidth'), 'no outer mobile horizontal overflow')
assert.equal(await run('window.pwned'), undefined)
const snapshot = await run('JobEditor.getDocument()')
await run('JobEditor.setDocument('+JSON.stringify(snapshot)+')')
assert.deepEqual(await run('JobEditor.getDocument()'),snapshot,'integration round trip retains document')
await run(`document.querySelector('[data-tab="direct"]').click()`)
assert.ok((await run('JobEditor.getHTML()')).includes('안전한 공고'),'HTML draft survives template round trip')
await run(`document.querySelector('[data-tab="template"]').click()`)
console.log('PASS: template retention, colors, rows, sections, rich/HTML sync, sanitization, sandbox previews, mobile width')
if (process.env.EDITOR_SCREENSHOT_DIR) {
  const fs = await import('node:fs/promises')
  const path = await import('node:path')
  await fs.mkdir(process.env.EDITOR_SCREENSHOT_DIR, {recursive:true})
  const mobile = await send('Page.captureScreenshot',{format:'png'})
  await fs.writeFile(path.join(process.env.EDITOR_SCREENSHOT_DIR,'mobile.png'),Buffer.from(mobile.data,'base64'))
  await send('Emulation.setDeviceMetricsOverride',{width:1180,height:1100,deviceScaleFactor:1,mobile:false})
  await send('Page.reload')
  await new Promise(resolve => setTimeout(resolve,300))
  const desktop = await send('Page.captureScreenshot',{format:'png'})
  await fs.writeFile(path.join(process.env.EDITOR_SCREENSHOT_DIR,'desktop.png'),Buffer.from(desktop.data,'base64'))
}
ws.close()
