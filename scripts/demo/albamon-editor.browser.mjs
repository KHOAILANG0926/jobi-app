import assert from 'node:assert/strict'
const pages = await (await fetch((process.env.CDP_URL || 'http://127.0.0.1:9222') + '/json')).json()
const page = pages.find(p => p.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
await new Promise(resolve => ws.addEventListener('open', resolve, { once: true }))
let id = 0
const pending = new Map()
ws.addEventListener('message', event => { const msg = JSON.parse(event.data); if(msg.id) { const p = pending.get(msg.id); pending.delete(msg.id); msg.error ? p.reject(msg.error) : p.resolve(msg.result) } })
const send = (method, params = {}) => new Promise((resolve, reject) => { const n = ++id; pending.set(n,{resolve,reject}); ws.send(JSON.stringify({id:n,method,params})) })
async function run(expression) { const r = await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true}); if(r.exceptionDetails) throw new Error(r.exceptionDetails.text+': '+JSON.stringify(r.exceptionDetails.exception)); return r.result.value }
await send('Page.enable')
await send('Network.enable')
await send('Network.setCacheDisabled',{cacheDisabled:true})
await send('Page.navigate', {url:(process.env.EDITOR_URL || 'http://127.0.0.1:8093/public/demos/albamon-editor/') + (process.env.EDITOR_URL?.includes('?') ? '&' : '?') + '_test=' + Date.now()})
await new Promise(resolve => setTimeout(resolve, 700))
