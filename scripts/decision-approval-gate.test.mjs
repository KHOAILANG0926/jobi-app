assert.ok(!/decision-approval-gate[^\n]*\n(?:[^\n]*\n){0,6}[^\n]*continue-on-error/.test(wf), '승인 검사 단계에 continue-on-error 금지')
assert.ok(/types:\s*\[[^\]]*labeled[^\]]*\]/.test(wf), '라벨이 붙을 때도 검사가 다시 돈다(needs-lee를 늦게 붙여도 반영)')
